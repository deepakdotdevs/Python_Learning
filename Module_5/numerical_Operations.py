# Numerical operations on list elements : 

numbers = [10, 4,20, -1,  5.5, 7, 1] # when we use 'Hi' or a string in the list, it falls an error

# finding the smallest and minimum of the list
# function called min()
print(f"Smallest number: {min(numbers)}")

# max() : Finding biggest num
print(f"Biggest number: {max(numbers)}")

# sum() : find the total of the nos in the list
print(f"The Total of Numbers is: {sum(numbers)}")
