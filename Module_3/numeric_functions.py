# Numeric functions are built-in functions used to perform operations on numbers, such as rounding, finding absolute values, and calculating powers.

# max() - Returns the largest value
print(max(10,20,30,25,19,2))

# min() - Returns the smallest value
print(min(10, 20, 5))

# abs() - Returns absolute value
print(abs(-2020))

# pow() - Calculates power
print(pow(2,3))

