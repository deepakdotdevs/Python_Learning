# Arithmetic Operators : Arithmetic operators are used to perform mathematical calculations such as addition, subtraction, multiplication, and division.

a = 10
b = 3
# addition operator :
print(a+b)
# substraction operator :
print(a-b)
# Multiplication Operator :
print(a*b)
# Division Operator :
print(a/b)
# Floor Division Operator (without decimal division part) 
print(a//b)
print(20/3)
print(20//3)
# Modulus Operator : Gives reminder
print(a%b)
# Exponential Operator : count powers
print(a**b)
print(20**3)

