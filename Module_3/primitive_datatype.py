# Data Type - Types of data that are being used inside our program for manipulation and storing purposes

# Primitive data type - Primitive data types are the basic types used to represent values in a program.
# eg; int (integer numbers), float (decimal numbers), bool (True or False Values), str (Text or strings), None


# integers : Means whole nos
age = 21
print(age)
print(type(age)) # to check what kind of data is we use type()

# floats : 
percent = 87.5
print(percent)
print(type(percent))

print(10+30) # interger + integer
print(10+32.2) # integer + float
print(3.5+20.1) # float + float

# strings : 
name = "Mr. Deepak"
print(name)
print(type(name))

# Boolean : 
val1 = True
print(val1)
print(type(val1))

val2 = False
print(val2)
print(type(val2))

# None : This data type is used to store the value which is not known or it is empty or a no value.
val3 = None
print(val3)
print(type(val3))
