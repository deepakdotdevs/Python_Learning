# Literals are fixed values written directly in a Python program. They represent data such as numbers, text, and Boolean values.

# Types of Literals in Python : 

# 1. Number Literals : Values representing numbers.

age = 21 # integer
price = 99.5 # float
num = 3 + 4j # complex

# 2. String Literals : A sequence of characters enclosed in quotes.

name = "Deepak"
city = 'Ujina'
message = """Hi, there !!"""

print("""Hi,
there
how are you,
are you fine well !!""")

print("""Hi,\nhow are you.\nare you well !!""")

# 3. Boolean Literals : Represent truth values. T in True and F in false. Used in cased where we have to check some conditions

is_student = True
is_working = False

# 4. Special Literal : None. Represents the absence of a value. represent no value or empty value

result = None